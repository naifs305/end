// ─────────────────────────────────────────────────────────────
// تهريب قيم فلاتر LDAP وفق RFC 4515.
// وحدة نقية بلا اعتماديات — نبني الفلاتر بأنفسنا و ldapts لا يهرّب
// نيابةً عنا، فأي قيمة تأتي من المستخدم يجب أن تمرّ من هنا أولاً.
// ─────────────────────────────────────────────────────────────

function escapeLdapFilter(value) {
  return value.replace(/[\\*()\x00]/g, (c) =>
    ({ '\\': '\\5c', '*': '\\2a', '(': '\\28', ')': '\\29' }[c] ?? '\\00'),
  );
}

module.exports = { escapeLdapFilter };
