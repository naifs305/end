import { describe, it, expect } from 'vitest';

const { parseLmsSchedule, cleanSessionTitle } = require('./lmsSchedule');

// نص بالهيئة التي يُنسخ بها جدول الدورة من منصة التدريب
const LMS = `
الجدول الزمني
يوم 1
(13-07-2026)
أيقونة
حفل الافتتاح
8:00 ص - 8:30 ص (30 دقيقة)
مشاهدة الطلاب
الحضور
1. مدخل إلى المقابلة الاستقصائية
8:30 ص - 10:00 ص (90 دقيقة)
العرض التقديمي.pdf
المدرب: د. محمد العمري
استراحة
10:00 ص - 10:30 ص (30 دقيقة)
بناء الألفة + إدارة الانطباع الأول
10:30 ص - 12:00 م (90 دقيقة)
بناء الألفة + إدارة الانطباع الأول
12:00 م - 1:00 م (60 دقيقة)
يوم 2
(14-07-2026)
مراجعة وتطبيقات عملية
8:00 ص - 9:00 ص (60 دقيقة)
قراءة السلوك غير اللفظي
٩:٠٠ ص - ١١:٠٠ ص (١٢٠ دقيقة)
رابط إلكتروني
QR
`;

describe('اللصق الذكي من منصة التدريب', () => {
  const out = parseLmsSchedule(LMS);

  it('يستخرج الجلسات بعناوينها وتواريخها وأوقاتها بنظام ٢٤ ساعة', () => {
    expect(out.map((s) => s.title)).toEqual([
      'حفل الافتتاح',
      'مدخل إلى المقابلة الاستقصائية',
      'بناء الألفة وإدارة الانطباع الأول',
      'قراءة السلوك غير اللفظي',
    ]);
    expect(out[0]).toMatchObject({ date: '2026-07-13', time: '08:00 - 08:30' });
    expect(out[3]).toMatchObject({ date: '2026-07-14', time: '09:00 - 11:00' });
  });

  it('يتجاهل الاستراحات والمراجعة وسطور الملفات والروابط', () => {
    const titles = out.map((s) => s.title).join('|');
    expect(titles).not.toMatch(/استراحة|مراجعة|pdf|رابط|QR|الحضور/);
  });

  it('يضمّ الجلسة الواحدة المقسومة على فترتين متتاليتين، ويحوّل الظهر صحيحاً', () => {
    expect(out[2].time).toBe('10:30 - 13:00');
  });

  it('يلتقط اسم المدرب المذكور بعد الجلسة', () => {
    expect(out[1].presenter).toBe('د. محمد العمري');
  });

  it('يقبل الجدول المنسوخ صفوفاً بخلايا، والتاريخ باسم الشهر', () => {
    const rows = 'الأحد 15 نوفمبر 2026\nالتخطيط الأمني للفعاليات\t09:00 - 10:30\nإدارة الحشود\t10:45 - 12:15\nغداء\t12:15 - 13:00';
    expect(parseLmsSchedule(rows)).toEqual([
      { title: 'التخطيط الأمني للفعاليات', date: '2026-11-15', time: '09:00 - 10:30', presenter: null },
      { title: 'إدارة الحشود', date: '2026-11-15', time: '10:45 - 12:15', presenter: null },
    ]);
  });

  it('نص لا جلسات فيه يعيد قائمة فارغة', () => {
    expect(parseLmsSchedule('مرحباً بكم في الدورة')).toEqual([]);
    expect(parseLmsSchedule('')).toEqual([]);
  });

  it('تنظيف العنوان لا يحذف رقماً هو جزء منه', () => {
    expect(cleanSessionTitle('2. أمن المعلومات.')).toBe('أمن المعلومات');
    expect(cleanSessionTitle('الجلسة 3: التحقيق الرقمي')).toBe('التحقيق الرقمي');
    expect(cleanSessionTitle('معايير ISO 27001')).toBe('معايير ISO 27001');
  });
});
