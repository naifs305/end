-- عمودان كان الكود يعتمد عليهما ولم يصلا قاعدة البيانات
-- -------------------------------------------------------------
-- اكتُشفا عند أول تطبيق فعلي للترحيلات على قاعدة البيانات:
--
--   • Course.closedAt    — لحظة الإقفال الفعلي، مرجع حساب تأخر
--                          الإقفال في مؤشرات الأداء
--   • User.tokenVersion  — إبطال الجلسات القائمة عند تغيير كلمة
--                          المرور، فلا تبقى جلسة قديمة صالحة
--
-- كلاهما معرَّف في مخطط البيانات ومستعمل في الكود منذ تحديثات
-- سابقة، لكن لم يُكتب لهما ملف ترحيل. فبدونهما يفشل أي استعلام
-- يقرأ المستخدم أو الدورة كاملة — أي المنصة كلها.
--
-- آمن لإعادة التشغيل، ولا يحذف بياناً: عمودان جديدان، أحدهما
-- اختياري والآخر له قيمة افتراضية.
-- =============================================================

ALTER TABLE "Course" ADD COLUMN IF NOT EXISTS "closedAt" TIMESTAMP(3);

ALTER TABLE "User" ADD COLUMN IF NOT EXISTS "tokenVersion" INTEGER NOT NULL DEFAULT 0;
